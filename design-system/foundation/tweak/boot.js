/* Tweak mode — boot
   Loaded by shared.js (#edit in the URL or Alt+Shift+E). Loads the modules below in order
   as classic scripts (works on file://, no build step) and starts the editor.

   Adding a module: create tweak/<name>.js that writes into window.DLTweakNS, add it here.
   Module contract, state and extension points: see tweak/README.md. */
(function () {
  'use strict';
  if (window.DLTweak) { window.DLTweak.on(); return; }
  if (window.DLTweakNS && window.DLTweakNS.booting) return;

  var MODULES = [
    'core.js',          // namespace, state, registries, helpers
    'tokens.js',        // DS tokens + full palette
    'editor-icons.js',  // Lucide icons for the editor UI
    'glyphs.js',        // every ReviewPro icon name (generated by build-icons.py)
    'components.js',    // component props registry (variants from shared.css)
    'library.js',       // insertable DS component snippets
    'source.js',        // HTML tokenizer + live DOM ↔ file alignment + attribute patching
    'file.js',          // File System Access: connect, save, conflicts
    'ops.js',           // undoable operations + history
    'ui.js',            // shadow-root shell, toolbar, notifications, help
    'overlays.js',      // canvas overlays: hover, selection, spacing, measure, drop line
    'similar.js',       // similar elements: edits apply to all of them (scope bar)
    'kiro-log.js',      // tweak-changes.md next to the page: net changes + steps for Kiro
    'comments.js',      // comment tool: pins on elements, written for Kiro into tweak-changes.md
    'fields.js',        // token fields, token dropdown, scrubbing
    'color-picker.js',  // palette popover
    'icon-picker.js',   // icon popover (rp-icons.css in the editor)
    'inspector.js',     // right panel shell: header, path, actions, sections
    'sections.js',      // inspector sections: props, layout, padding, margin, text, fill
    'size.js',          // size section (W / H: fixed, hug, fill) + resize handles
    'position.js',      // position section: ignore auto layout (absolute), X / Y, free move + nudge
    'wrap.js',          // ⇧A / ⌘G: wrap the selection in a new auto layout frame
    'swap.js',          // swap component section: button ↔ checkbox ↔ …, text list ↔ text group
    'library-panel.js', // + panel: insert / replace with DS components, drag in
    'versions.js',      // version history: copies in .tweak-history/ before each overwrite, restore
    'dnd.js',           // drop-target rules for drag & drop (pure, tested by .kiro/scripts/dnd-test.js)
    'interactions.js',  // pointer + keyboard, text editing, drag & drop
    'main.js'           // on / off, public API
  ];

  var STAMP = Date.now();
  var me = document.currentScript || document.querySelector('script[src*="tweak/boot.js"]');
  var base = me ? me.src.replace(/boot\.js(\?.*)?$/, '') : 'tweak/';
  var NS = window.DLTweakNS = window.DLTweakNS || {};
  NS.base = base;
  NS.stamp = STAMP;
  NS.booting = true;

  var i = 0;
  (function next() {
    if (i >= MODULES.length) { NS.booting = false; NS.start(); return; }
    var s = document.createElement('script');
    s.src = base + MODULES[i++] + '?v=' + STAMP; /* never mix cached modules from an older kit */
    s.onload = next;
    s.onerror = function () { console.error('[Tweak] failed to load ' + s.src); NS.booting = false; };
    document.head.appendChild(s);
  })();
})();
